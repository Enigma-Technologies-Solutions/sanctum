// The /download/ page and web/assets/download.js, generated from one list so they cannot drift.
//
// Every link points at GitHub's `releases/latest/download/<name>` address, which always serves
// the newest published release. That only works because the release workflow also attaches
// each installer under the stable names below (.github/workflows/release.yml, "Attach
// installers under stable names"). Change a name here and there together.
//
// The page works with no script: it lists every installer. The script is the one piece of
// JavaScript on the site. It runs from 'self' (no inline script, no third party), reads the
// browser's platform and points every `a[data-download]` link straight at the right file.
// When it cannot tell, for example on a phone or an unknown Linux architecture, it changes
// nothing and the links keep going to this page.

