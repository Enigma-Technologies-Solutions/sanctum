/** Every page loads assets/download.js from 'self' and nothing else; take that one tag out. */
export const withoutDownloadScript = (html) => html.replace(/<script src="(?:\.\/|(?:\.\.\/)+)assets\/download\.js" defer><\/script>\n?/g, '');

const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

/** The text of web/assets/download.js. */
export function downloadScript() {
  const pick = Object.fromEntries(PLATFORMS.map((p) => [p.key, { file: p.files[0].file, name: p.name.replace(/,.*/, '') }]));
  return `// Generated by scripts/build-download.mjs from scripts/lib/download.mjs. Do not edit.
//
// The only script on this site. It points the Download buttons straight at the installer for
// this device. Without it, or when the device is not recognised, they go to /download/.
(function () {
  'use strict';
  var BASE = ${JSON.stringify(LATEST)};
  var PICK = ${JSON.stringify(pick)};
  var nav = window.navigator;
  var ua = nav.userAgent || '';
  var platform = (nav.userAgentData && nav.userAgentData.platform) || nav.platform || '';
  var key = null;
  if (/iPhone|iPad|iPod|Android/i.test(ua) || /CrOS/.test(ua)) key = null;
  // iPadOS reports itself as a Mac; a touch screen gives it away.
  else if (/Mac/i.test(platform) || /Macintosh/.test(ua)) key = nav.maxTouchPoints > 1 ? null : 'mac';
  else if (/Win/i.test(platform) || /Windows/.test(ua)) key = 'win';
  else if (/Linux/i.test(platform) || /Linux|X11/.test(ua)) {
    var arch = platform + ' ' + ua;
    if (/aarch64|arm64/i.test(arch)) key = 'linux-arm64';
    else if (/x86_64|amd64/i.test(arch)) key = 'linux-x86_64';
  }
  var hit = key && PICK[key];
  if (!hit) return;
  var links = document.querySelectorAll('a[data-download]');
  for (var i = 0; i < links.length; i++) {
    var a = links[i];
    a.href = BASE + hit.file;
    a.removeAttribute('rel');
    if (a.getAttribute('data-download') === 'label') {
      for (var n = a.firstChild; n; n = n.nextSibling) {
        if (n.nodeType === 3 && /\\S/.test(n.nodeValue)) {
          n.nodeValue = 'Download for ' + hit.name + ' ';
          break;
        }
      }
    }
  }
  var mark = document.querySelector('[data-platform="' + key + '"]');
  if (mark) mark.classList.add('dl--here');
})();
`;
}

/** /download/: every installer, grouped by platform. */
export function downloadPage({ siteUrl }) {
  const cards = PLATFORMS.map((p) => {
    const [first, ...rest] = p.files;
    const others = rest.length
      ? `\n        <p class="fine">Also: ${rest.map((f) => `<a href="${esc(LATEST + f.file)}">${esc(f.label)}</a>`).join(', ')}</p>`
      : '';
    return `
      <article class="card app" data-platform="${esc(p.key)}">
        <h2 class="app__name">${esc(p.name)} <span class="tag dl__here">Your device</span></h2>
        <p class="app__desc">${esc(p.note)}</p>
        <a class="btn btn--volt btn--sm" href="${esc(LATEST + first.file)}">Download ${esc(first.label)}</a>${others}
      </article>`;
  }).join('\n');
  const body = `    <p class="eyebrow">Download</p>
    <h1 class="h2">Download Sanctum</h1>
    <p class="lede">Free for individuals, with no account. Each link downloads the latest release directly. Older versions, checksums and the changelog are on the <a href="https://github.com/Enigma-Technologies-Solutions/sanctum/releases" rel="noopener">releases page</a>.</p>
    <div class="apps__list">${cards}
    </div>
    <p class="fine">Sanctum checks for updates on its own and asks before installing one. Every update is signature-checked against a key built into the app.</p>`;
  return shell({
    title: 'Download | Sanctum',
    description: 'Download Sanctum for macOS, Windows or Linux.',
    canonical: `${siteUrl}/download/`,
    depth: 1,
    siteUrl,
    body,
  });
}
